"""Regenerate Sources/LLMPrices/PricesJSON.swift from llm-prices' prices.json.

    python scripts/sync.py                    # latest prices.json from GitHub
    python scripts/sync.py ../llm-prices/prices.json

The JSON is embedded as a raw string literal, byte for byte, so the Swift package reads the
same table as the Rust crate, the Python package, the Go module and the JavaScript module.
"""
import json
import pathlib
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/Mattbusel/llm-prices/main/prices.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "Sources" / "LLMPrices" / "PricesJSON.swift"


def main() -> None:
    if len(sys.argv) > 1:
        text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL, timeout=30) as r:
            text = r.read().decode("utf-8")
    doc = json.loads(text)
    if len(doc["models"]) < 50:
        sys.exit("prices.json has fewer than 50 rows")
    if '"#' in text:
        sys.exit('prices.json contains "#, which would end the raw string literal')
    body = text.rstrip("\n")
    OUT.write_text(
        "// Generated by scripts/sync.py from https://github.com/Mattbusel/llm-prices/blob/main/prices.json\n"
        f"// Table generated {doc['generated']}, {len(doc['models'])} rows. Do not edit by hand.\n\n"
        "let pricesJSON = #\"\"\"\n" + body + "\n\"\"\"#\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {OUT} ({len(doc['models'])} rows, generated {doc['generated']})")


if __name__ == "__main__":
    main()
